# Windows-only: run separately from server_test.rb; no fixture command override.
require "tmpdir"
require "fileutils"
require "minitest/autorun"
require "rack/test"
require "rack/tempfile_reaper"
require "open3"

abort 'Set IMAGE_OPTIMIZER_FIXTURES to the corpus generated by scripts/new-test-images.ps1.' unless ENV['IMAGE_OPTIMIZER_FIXTURES']
abort 'Real WIC integration requires Windows.' unless Gem.win_platform?
NATIVE_TEST_STORAGE = Dir.mktmpdir('wic-api-')
ENV['IMAGE_OPTIMIZER_STORAGE'] = NATIVE_TEST_STORAGE
ENV['RACK_ENV'] = 'test'
require_relative '../app/server'
Minitest.after_run do
  ImageOptimizer::STORAGE_LOCK.close
  FileUtils.remove_entry(NATIVE_TEST_STORAGE)
end

class NativeIntegrationTest < Minitest::Test
  include Rack::Test::Methods
  def app = Rack::TempfileReaper.new(ImageOptimizer::Server)

  def upload(name)
    Rack::Test::UploadedFile.new(File.join(ENV.fetch('IMAGE_OPTIMIZER_FIXTURES'), name), 'application/octet-stream')
  end

  def submit(images, format: 'keep')
    post '/api/jobs', { 'images' => images, 'format' => format, 'quality' => '82', 'max_width' => '1800', 'max_height' => '1800' }
    assert_equal 202, last_response.status, last_response.body
    id = JSON.parse(last_response.body)['id']
    deadline = Process.clock_gettime(Process::CLOCK_MONOTONIC) + 120
    loop do
      get "/api/jobs/#{id}"
      assert_equal 200, last_response.status
      job = JSON.parse(last_response.body)
      return job if %w[done failed].include?(job['status'])
      raise 'Timed out waiting for WIC job' if Process.clock_gettime(Process::CLOCK_MONOTONIC) > deadline
      sleep 0.1
    end
  end

  def assert_decodable(bytes, format)
    path = File.join(NATIVE_TEST_STORAGE, "download-#{SecureRandom.uuid}.#{format}")
    File.binwrite(path, bytes)
    script = File.expand_path('../../scripts/assert-image.ps1', __dir__)
    # scripts/ is at repository root, two levels above backend/test.
    _stdout, stderr, result = Open3.capture3('powershell.exe', '-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', script,
      '-Path', path, '-Format', format, '-Width', '1800', '-Height', '900')
    assert result.success?, stderr
  end

  def test_real_upload_queue_processing_download_and_zip_for_all_four_formats
    job = submit(%w[png jpeg bmp tiff].map { |format| upload("landscape.#{format}") })
    assert_equal 'done', job['status'], job.inspect
    job['files'].each do |file|
      format = file.dig('metadata', 'format')
      get file['original_url']
      assert_equal 200, last_response.status
      assert_equal File.binread(File.join(ENV.fetch('IMAGE_OPTIMIZER_FIXTURES'), "landscape.#{format}")).b, last_response.body.b
      get "#{file['optimized_url']}?download=1"
      assert_equal 200, last_response.status
      assert_includes last_response.headers['content-disposition'], 'attachment'
      assert_decodable(last_response.body, format)
    end
    get "/api/jobs/#{job['id']}/export"
    assert_equal 200, last_response.status
    Zip::File.open_buffer(last_response.body) do |zip|
      assert_equal 4, zip.entries.length
      job['files'].each do |file|
        entry = zip.find_entry(file['output_name'])
        refute_nil entry
        assert_decodable(entry.get_input_stream.read, file.dig('metadata', 'format'))
      end
    end
  end

  def test_real_partial_failure_allows_successful_downloads
    job = submit([upload('landscape.png'), upload('corrupt.png')], format: 'jpeg')
    assert_equal 'failed', job['status']
    assert_equal %w[done failed], job['files'].map { |file| file['status'] }
    get job['files'].first['optimized_url']
    assert_equal 200, last_response.status
    assert_decodable(last_response.body, 'jpeg')
    get "/api/jobs/#{job['id']}/export"
    assert_equal 200, last_response.status
    Zip::File.open_buffer(last_response.body) { |zip| assert_equal 1, zip.entries.length }
    assert_empty Dir.glob(File.join(ImageOptimizer::OUTPUTS_DIR, job['id'], '.processing-*'))
  end
end
